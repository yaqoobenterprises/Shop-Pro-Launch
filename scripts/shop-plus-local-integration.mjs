function totp(secret) {
  const alphabet="ABCDEFGHIJKLMNOPQRSTUVWXYZ234567";
  let bits="";
  for (const char of secret.replace(/=+$/,"").toUpperCase()) { const index=alphabet.indexOf(char); assert.ok(index>=0); bits+=index.toString(2).padStart(5,"0"); }
  const bytes=Buffer.from((bits.match(/.{8}/g)||[]).map(chunk=>parseInt(chunk,2)));
  const counter=Buffer.alloc(8); counter.writeBigUInt64BE(BigInt(Math.floor(Date.now()/30000)));
  const mac=createHmac("sha1",bytes).update(counter).digest();
  return String((mac.readUInt32BE(mac[mac.length-1]&15)&0x7fffffff)%1000000).padStart(6,"0");
}
